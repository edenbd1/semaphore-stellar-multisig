// Domain-separated fixture for the ConfidentialDao: two depth-2 proofs from DISTINCT members,
// both bound to the SAME proposal: message == hash(PAYLOAD action) and scope == DOMAIN-BOUND
// scope == keccak256( ascii(CONTRACT strkey) || SCOPE_SEED ) >> 8. On-chain approve() recomputes
// the scope via domain_scope_hash(current_contract_address, proposal.scope_seed).
import { Identity } from "@semaphore-protocol/identity"
import { Group } from "@semaphore-protocol/group"
import { generateProof, unpackGroth16Proof, verifyProof } from "@semaphore-protocol/proof"
import * as snarkjs from "snarkjs"
import { keccak256, toBeHex, concat, toUtf8Bytes, getBytes } from "ethers"
import { StrKey } from "@stellar/stellar-sdk"
import { readFileSync, writeFileSync } from "fs"
import { tmpdir } from "os"
import { join } from "path"

const MULTISIG = "/Users/eden/data/semaphore-stellar-multisig"
const ART = join(tmpdir(), "snark-artifacts", "semaphore", "4.13.0")
const SNARK = { wasm: join(ART, "semaphore-2.wasm"), zkey: join(ART, "semaphore-2.zkey") }
const hash = (m) => (BigInt(keccak256(toBeHex(m, 32))) >> 8n).toString()

const CONTRACT_ID = getBytes(keccak256(toUtf8Bytes("semaphore-stellar/dao/domain-v1")))
const CONTRACT = StrKey.encodeContract(Buffer.from(CONTRACT_ID))

const PAYLOAD_HEX = "22".repeat(32)          // proposal action digest (bound as message)
const payloadBig = BigInt("0x" + PAYLOAD_HEX)
const SEED_HEX = "44".repeat(32)             // proposal scope seed

const rawscopeHex = keccak256(concat([toUtf8Bytes(CONTRACT), getBytes("0x" + SEED_HEX)]))
const scopeBig = BigInt(rawscopeHex)
if (toBeHex(scopeBig, 32) !== rawscopeHex) throw new Error("scope encoding mismatch")

const A = new Identity(), B = new Identity(), C = new Identity()
const group = new Group([A.commitment, B.commitment, C.commitment])
const vkey = JSON.parse(readFileSync(`${MULTISIG}/fixtures/vkey-depth2.json`, "utf8"))
const hm = hash(payloadBig), hs = hash(scopeBig)

async function mk(id) {
    const p = await generateProof(id, group, payloadBig, scopeBig, 2, SNARK)
    if (!(await verifyProof(p))) throw new Error("lib verifyProof failed")
    const u = unpackGroth16Proof(p.points)
    const pub = [p.merkleTreeRoot.toString(), p.nullifier.toString(), hm, hs]
    if (!(await snarkjs.groth16.verify(vkey, pub, u))) throw new Error("ground-truth verify failed")
    return { root: p.merkleTreeRoot.toString(), nullifier: p.nullifier.toString(), u }
}
const pa = await mk(A)
const pb = await mk(B)
if (pa.root !== pb.root) throw new Error("root mismatch")

const be32 = (d) => BigInt(d).toString(16).padStart(64, "0")
const arr = (hex) => "[" + hex.match(/../g).map((x) => "0x" + x).join(", ") + "]"
const G1 = (q) => arr(be32(q[0]) + be32(q[1]))
const G2u = (u) => arr(be32(u.pi_b[0][1]) + be32(u.pi_b[0][0]) + be32(u.pi_b[1][1]) + be32(u.pi_b[1][0]))

const L = ["// AUTO-GENERATED by tools/gen-dao-fixture-domain.mjs — do not edit by hand.",
    "// Two depth-2 proofs from distinct members: message == hash(PAYLOAD action),",
    "// scope == keccak256( ascii(CONTRACT strkey) || SCOPE_SEED ) >> 8 (domain-bound).", "",
    `pub const PAYLOAD: [u8; 32] = ${arr(PAYLOAD_HEX)};`,
    `pub const SCOPE_SEED: [u8; 32] = ${arr(SEED_HEX)};`,
    `/// The DAO contract address the proposal scope is bound to; the test registers here.`,
    `pub const CONTRACT: &str = "${CONTRACT}";`,
    `pub const ROOT: [u8; 32] = ${arr(be32(pa.root))};`,
    "", "// Member A", `pub const NUL_A: [u8; 32] = ${arr(be32(pa.nullifier))};`,
    `pub const A_A: [u8; 64] = ${G1(pa.u.pi_a)};`,
    `pub const A_B: [u8; 128] = ${G2u(pa.u)};`,
    `pub const A_C: [u8; 64] = ${G1(pa.u.pi_c)};`,
    "", "// Member B", `pub const NUL_B: [u8; 32] = ${arr(be32(pb.nullifier))};`,
    `pub const B_A: [u8; 64] = ${G1(pb.u.pi_a)};`,
    `pub const B_B: [u8; 128] = ${G2u(pb.u)};`,
    `pub const B_C: [u8; 64] = ${G1(pb.u.pi_c)};`,
    "", "// Verification key (depth 2)",
    `pub const VK_ALPHA: [u8; 64] = ${G1([vkey.vk_alpha_1[0], vkey.vk_alpha_1[1]])};`,
    `pub const VK_BETA: [u8; 128] = ${arr(be32(vkey.vk_beta_2[0][1]) + be32(vkey.vk_beta_2[0][0]) + be32(vkey.vk_beta_2[1][1]) + be32(vkey.vk_beta_2[1][0]))};`,
    `pub const VK_GAMMA: [u8; 128] = ${arr(be32(vkey.vk_gamma_2[0][1]) + be32(vkey.vk_gamma_2[0][0]) + be32(vkey.vk_gamma_2[1][1]) + be32(vkey.vk_gamma_2[1][0]))};`,
    `pub const VK_DELTA: [u8; 128] = ${arr(be32(vkey.vk_delta_2[0][1]) + be32(vkey.vk_delta_2[0][0]) + be32(vkey.vk_delta_2[1][1]) + be32(vkey.vk_delta_2[1][0]))};`,
    ""]
vkey.IC.forEach((q, i) => L.push(`pub const VK_IC_${i}: [u8; 64] = ${G1(q)};`))
L.push("")
writeFileSync(`${MULTISIG}/contracts/dao/src/fixture.rs`, L.join("\n"))
console.log("OK: dao ground-truth verified (domain-bound). CONTRACT =", CONTRACT)
process.exit(0)
