// Ground-truth fixture for the __check_auth account test with ROBUST DOMAIN SEPARATION.
//
// The circuit `scope` is derived from the account's OWN contract address so a proof minted
// for this deployment cannot be replayed against another contract that shares the group root:
//
//   rawscope = keccak256( ascii(contract_strkey) || scope_seed )          (32 bytes)
//   scopeField (4th public signal) = keccak256( toBeHex(rawscope,32) ) >> 8
//
// On-chain the contract recomputes exactly this from env.current_contract_address() and the
// stored scope_seed (see domain_scope_hash in contracts/account/src/lib.rs). No circuit or
// ceremony change — only the field element fed as `scope`.
import { Identity } from "@semaphore-protocol/identity"
import { Group } from "@semaphore-protocol/group"
import { generateProof, unpackGroth16Proof, verifyProof } from "@semaphore-protocol/proof"
import * as snarkjs from "snarkjs"
import { keccak256, toBeHex, concat, toUtf8Bytes, getBytes } from "ethers"
import { StrKey } from "@stellar/stellar-sdk"
import { readFileSync, writeFileSync } from "fs"
import { tmpdir } from "os"
import { join } from "path"

const MULTISIG = "/Users/eden/data/semaphore-stellar-multisig"
// Use the locally cached snark artifacts (depth 2) so no network fetch is attempted.
const ART = join(tmpdir(), "snark-artifacts", "semaphore", "4.13.0")
const SNARK = { wasm: join(ART, "semaphore-2.wasm"), zkey: join(ART, "semaphore-2.zkey") }
const hash = (m) => (BigInt(keccak256(toBeHex(m, 32))) >> 8n).toString()

// Deterministic, self-documenting FIXED test identity for this contract. The Rust test
// registers the contract at exactly this strkey (env.register_at), so the on-chain
// current_contract_address() matches the domain baked into the proof below.
const CONTRACT_ID = getBytes(keccak256(toUtf8Bytes("semaphore-stellar/account/domain-v1"))) // 32B
const CONTRACT = StrKey.encodeContract(Buffer.from(CONTRACT_ID))                            // "C..."

// Chosen signature payload (32 bytes) and account scope seed.
const PAYLOAD_HEX = "11".repeat(32)
const payloadBig = BigInt("0x" + PAYLOAD_HEX)
const SEED_HEX = "22".repeat(32)

// Domain-bound scope: keccak256( ascii(strkey) || seed ).
const rawscopeHex = keccak256(concat([toUtf8Bytes(CONTRACT), getBytes("0x" + SEED_HEX)]))
const scopeBig = BigInt(rawscopeHex)
// Sanity: the field element we feed must round-trip through toBeHex(.,32) to the same 32 bytes.
if (toBeHex(scopeBig, 32) !== rawscopeHex) throw new Error("scope encoding mismatch")

const a = new Identity(), b = new Identity(), c = new Identity()
const group = new Group([a.commitment, b.commitment, c.commitment])
const proof = await generateProof(a, group, payloadBig, scopeBig, 2, SNARK)
if (!(await verifyProof(proof))) throw new Error("lib verifyProof failed")

const u = unpackGroth16Proof(proof.points)
const publicSignals = [
    proof.merkleTreeRoot.toString(),
    proof.nullifier.toString(),
    hash(proof.message), // == keccak256(PAYLOAD)>>8
    hash(proof.scope),   // == keccak256(rawscope)>>8  (domain-bound)
]
const vkey = JSON.parse(readFileSync(`${MULTISIG}/fixtures/vkey-depth2.json`, "utf8"))
if (!(await snarkjs.groth16.verify(vkey, publicSignals, u))) throw new Error("ground-truth verify failed")

const be32 = (d) => BigInt(d).toString(16).padStart(64, "0")
const arr = (hex) => "[" + hex.match(/../g).map((x) => "0x" + x).join(", ") + "]"
const G1 = (p) => arr(be32(p[0]) + be32(p[1]))
const G2 = (p) => arr(be32(p[0][1]) + be32(p[0][0]) + be32(p[1][1]) + be32(p[1][0]))

const L = ["// AUTO-GENERATED by tools/gen-account-fixture-domain.mjs — do not edit by hand.",
    "// A Semaphore proof bound to PAYLOAD (as message) and a DOMAIN-BOUND scope:",
    "//   scope = keccak256( ascii(CONTRACT strkey) || SCOPE_SEED ), re-hashed >>8, depth 2.", ""]
L.push(`pub const PAYLOAD: [u8; 32] = ${arr(PAYLOAD_HEX)};`)
L.push(`pub const SCOPE_SEED: [u8; 32] = ${arr(SEED_HEX)};`)
L.push(`/// The contract address the proof's scope is bound to; the test registers here.`)
L.push(`pub const CONTRACT: &str = "${CONTRACT}";`)
L.push(`pub const ROOT: [u8; 32] = ${arr(be32(publicSignals[0]))};`)
L.push(`pub const NULLIFIER: [u8; 32] = ${arr(be32(publicSignals[1]))};`)
L.push("", "// Proof points",
    `pub const PROOF_A: [u8; 64] = ${G1([u.pi_a[0].toString(), u.pi_a[1].toString()])};`,
    `pub const PROOF_B: [u8; 128] = ${G2([[u.pi_b[0][0].toString(), u.pi_b[0][1].toString()], [u.pi_b[1][0].toString(), u.pi_b[1][1].toString()]])};`,
    `pub const PROOF_C: [u8; 64] = ${G1([u.pi_c[0].toString(), u.pi_c[1].toString()])};`,
    "", "// Verification key (depth 2)",
    `pub const VK_ALPHA: [u8; 64] = ${G1([vkey.vk_alpha_1[0], vkey.vk_alpha_1[1]])};`,
    `pub const VK_BETA: [u8; 128] = ${G2(vkey.vk_beta_2)};`,
    `pub const VK_GAMMA: [u8; 128] = ${G2(vkey.vk_gamma_2)};`,
    `pub const VK_DELTA: [u8; 128] = ${G2(vkey.vk_delta_2)};`,
    "")
vkey.IC.forEach((p, i) => L.push(`pub const VK_IC_${i}: [u8; 64] = ${G1(p)};`))
L.push("")
writeFileSync(`${MULTISIG}/contracts/account/src/fixture.rs`, L.join("\n"))
console.log("OK: ground-truth verified (domain-bound).")
console.log("  CONTRACT =", CONTRACT)
console.log("  wrote contracts/account/src/fixture.rs")
process.exit(0) // snarkjs leaves BN128 worker threads alive; force a clean exit.
