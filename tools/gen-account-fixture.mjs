// Ground-truth fixture for the __check_auth custom account test: a Semaphore proof whose
// circuit message == a chosen 32-byte payload and whose scope == the account scope, so the
// on-chain __check_auth (which recomputes message := keccak256(payload)>>8) verifies.
import { Identity } from "@semaphore-protocol/identity"
import { Group } from "@semaphore-protocol/group"
import { generateProof, unpackGroth16Proof, verifyProof } from "@semaphore-protocol/proof"
import * as snarkjs from "snarkjs"
import { keccak256, toBeHex } from "ethers"
import { readFileSync, writeFileSync } from "fs"

const hash = (m) => (BigInt(keccak256(toBeHex(m, 32))) >> 8n).toString()

// Chosen signature payload (32 bytes) and account scope.
const PAYLOAD_HEX = "11".repeat(32)
const payloadBig = BigInt("0x" + PAYLOAD_HEX)
const SCOPE = "semaphore-account-scope"

const a = new Identity(), b = new Identity(), c = new Identity()
const group = new Group([a.commitment, b.commitment, c.commitment])
// message == payload so the circuit's hash(message) equals on-chain keccak256(payload)>>8.
const proof = await generateProof(a, group, payloadBig, SCOPE)
if (!(await verifyProof(proof))) throw new Error("lib verifyProof failed")

const u = unpackGroth16Proof(proof.points)
const publicSignals = [
    proof.merkleTreeRoot.toString(),
    proof.nullifier.toString(),
    hash(proof.message), // == keccak256(PAYLOAD)>>8
    hash(proof.scope),   // == account scope hash
]
const vkey = JSON.parse(readFileSync("../fixtures/vkey-depth2.json", "utf8"))
if (!(await snarkjs.groth16.verify(vkey, publicSignals, u))) throw new Error("ground-truth verify failed")

const be32 = (d) => BigInt(d).toString(16).padStart(64, "0")
const arr = (hex) => "[" + hex.match(/../g).map((x) => "0x" + x).join(", ") + "]"
const G1 = (p) => arr(be32(p[0]) + be32(p[1]))
const G2 = (p) => arr(be32(p[0][1]) + be32(p[0][0]) + be32(p[1][1]) + be32(p[1][0]))

const L = ["// AUTO-GENERATED by tools/gen-account-fixture.mjs — do not edit by hand.",
    "// A Semaphore proof bound to PAYLOAD (as message) and the account SCOPE, depth 2.", ""]
L.push(`pub const PAYLOAD: [u8; 32] = ${arr(PAYLOAD_HEX)};`)
L.push(`pub const ROOT: [u8; 32] = ${arr(be32(publicSignals[0]))};`)
L.push(`pub const NULLIFIER: [u8; 32] = ${arr(be32(publicSignals[1]))};`)
L.push(`pub const SCOPE_HASH: [u8; 32] = ${arr(be32(publicSignals[3]))};`)
L.push("", "// Proof points",
    `pub const PROOF_A: [u8; 64] = ${G1([u.pi_a[0].toString(), u.pi_a[1].toString()])};`,
    `pub const PROOF_B: [u8; 128] = ${G2([[u.pi_b[0][0].toString(), u.pi_b[0][1].toString()], [u.pi_b[1][0].toString(), u.pi_b[1][1].toString()]])};`,
    `pub const PROOF_C: [u8; 64] = ${G1([u.pi_c[0].toString(), u.pi_c[1].toString()])};`,
    "", "// Verification key (depth 2)",
    `pub const VK_ALPHA: [u8; 64] = ${G1([vkey.vk_alpha_1[0], vkey.vk_alpha_1[1]])};`,
    `pub const VK_BETA: [u8; 128] = ${G2(vkey.vk_beta_2)};`,
    `pub const VK_GAMMA: [u8; 128] = ${G2(vkey.vk_gamma_2)};`,
    `pub const VK_DELTA: [u8; 128] = ${G2(vkey.vk_delta_2)};`,
    "")
vkey.IC.forEach((p, i) => L.push(`pub const VK_IC_${i}: [u8; 64] = ${G1(p)};`))
L.push("")
writeFileSync("../contracts/account/src/fixture.rs", L.join("\n"))
console.log("OK: ground-truth verified; wrote contracts/account/src/fixture.rs")
